# Deterministic, Float64 CUDA implementation of the corrected full-curl RHS.
# This file is intentionally a small, opt-in backend: it supports the root
# geometry only and never silently falls back to a host implementation.
using CUDA

struct GPUFullCurlScalars
    nx::Int32; ny::Int32; hx::Float64; hy::Float64
    kappa::Float64; u::Float64; gamma::Float64
    ceff::Float64; keff::Float64; t0::Float64
    eta_env::Float64; eta_hole::Float64; holewidth::Float64
    he::Float64; coverage::Float64
    tc1::Float64; tc2::Float64; tc3::Float64; tc1gap::Float64; tc3gap::Float64
    thermal::Int32
end

struct GPUFullCurlCache
    s::GPUFullCurlScalars
    currents::CuArray{Float64,1}
    sigma::CuArray{Float64,2}; eta::CuArray{Float64,2}; tc::CuArray{Float64,2}
    psi::CuArray{ComplexF64,2}; ax::CuArray{Float64,2}; ay::CuArray{Float64,2}; temp::CuArray{Float64,2}
    ux::CuArray{ComplexF64,2}; uy::CuArray{ComplexF64,2}
    dpsi::CuArray{ComplexF64,2}; rhspsi::CuArray{ComplexF64,2}
    dax::CuArray{Float64,2}; day::CuArray{Float64,2}; dt::CuArray{Float64,2}
    jsx::CuArray{Float64,2}; jsy::CuArray{Float64,2}; w::CuArray{Float64,2}
end

function _gpu_supported(p)
    p.Nx >= 3 && p.Ny >= 3 || throw(ArgumentError("GPU full-curl RHS requires Nx,Ny >= 3"))
    p.bc_x === :periodic || throw(ArgumentError("GPU full-curl RHS supports bc_x=:periodic only"))
    p.bc_y === :neumann || throw(ArgumentError("GPU full-curl RHS supports bc_y=:neumann only"))
    !p.loop || throw(ArgumentError("GPU full-curl RHS supports loop=false only"))
    p.field_side === :both || throw(ArgumentError("GPU full-curl RHS supports field_side=:both only"))
    !p.psi_y_zero || throw(ArgumentError("GPU full-curl RHS supports psi_y_zero=false only"))
    p.epsilon_type === :linear || throw(ArgumentError("GPU full-curl RHS supports epsilon_type=:linear only"))
    p.noise_strength == 0.0 || throw(ArgumentError("GPU full-curl RHS is deterministic; noise_strength must be zero"))
    return nothing
end

function _gpu_maps(p)
    # These are deliberately generated by the reference helpers, then copied
    # without alteration to the device.
    sigma = compute_sigma_distribution(p)
    eta = compute_eta_distribution(p)
    tc = compute_Tc_distribution(p)
    return sigma, eta, tc
end

function GPUFullCurlCache(p::TDGLThermalParams, currents::Vector{Float64})
    _gpu_supported(p)
    isempty(currents) && throw(ArgumentError("currents must not be empty"))
    nxy = (p.Nx + 1) * (p.Ny + 1); nax = p.Nx * (p.Ny + 1); nay = (p.Nx + 1) * p.Ny
    b = length(currents)
    s0 = GPUFullCurlScalars(Int32(p.Nx), Int32(p.Ny), p.hx, p.hy, p.kappa, p.u, p.gamma,
        p.C_eff, p.k_eff, p.T0, p.eta_env, p.eta_hole, p.holewidth, p.He,
        p.bc_y_coverage, p.Tc1, p.Tc2, p.Tc3, p.Tc1gap, p.Tc3gap,
        p.thermal_enabled ? Int32(1) : Int32(0))
    sigma, eta, tc = _gpu_maps(p)
    zc(n) = CUDA.zeros(ComplexF64, n, b); zr(n) = CUDA.zeros(Float64, n, b)
    # Store one immutable map column per batch so kernels never dereference a
    # host object or perform a scalar-indexed device lookup.
    sigma_d = CuArray(repeat(vec(sigma), 1, b)); eta_d = CuArray(repeat(vec(eta), 1, b)); tc_d = CuArray(repeat(vec(tc), 1, b))
    return GPUFullCurlCache(s0, CuArray(currents), sigma_d, eta_d, tc_d,
        zc(nxy), zr(nax), zr(nay), zr(nxy), zc(nax), zc(nay), zc(nxy), zc(nxy),
        zr(nax), zr(nay), zr(nxy), zr(nax), zr(nay), zr(nxy))
end

@inline _I(i,j,nx) = i + (j-1)*(nx+1)
@inline _IX(i,j,nx) = i + (j-1)*nx
@inline _IY(i,j,nx) = i + (j-1)*(nx+1)

function _k_unpack!(du,u,psi,ax,ay,temp,ux,uy,s)
    q = (CUDA.blockIdx().x-1)*CUDA.blockDim().x + CUDA.threadIdx().x
    b = CUDA.blockIdx().y; nx=Int(s.nx); ny=Int(s.ny); np=(nx+1)*(ny+1); na=nx*(ny+1); nb=(nx+1)*ny
    if q <= np
        psi[q,b]=u[q,b]; du[q,b]=0
    elseif q <= np+na
        k=q-np; ax[k,b]=real(u[q,b]); du[q,b]=0
    elseif q <= np+na+nb
        k=q-np-na; ay[k,b]=real(u[q,b]); du[q,b]=0
    elseif q <= np+na+nb+np
        k=q-np-na-nb; temp[k,b]=real(u[q,b]); du[q,b]=0
    end
    return
end

function _k_links!(psi,ax,ay,temp,ux,uy,s)
    q=(CUDA.blockIdx().x-1)*CUDA.blockDim().x+CUDA.threadIdx().x; b=CUDA.blockIdx().y
    nx=Int(s.nx); ny=Int(s.ny); np=(nx+1)*(ny+1); na=nx*(ny+1); nb=(nx+1)*ny
    if q<=na; ux[q,b]=cis(-s.hx*ax[q,b]); end
    if q<=nb; uy[q,b]=cis(-s.hy*ay[q,b]); end
    return
end

# Independent rows/edges in the first boundary pass can run in parallel.
# A separate second launch preserves the reference's x-then-y corner order.
function _k_bc_x!(psi,ax,ay,temp,curr,s)
    q=(CUDA.blockIdx().x-1)*CUDA.blockDim().x+CUDA.threadIdx().x
    b=CUDA.blockIdx().y; nx=Int(s.nx); ny=Int(s.ny); Lx=nx*s.hx; Ly=ny*s.hy
    h=curr[b]*Ly/(2*s.kappa*s.kappa); hu=-h+s.he; hl=h+s.he
    xl=-Lx/2+(1-s.coverage)*Lx/2; xr=Lx/2-(1-s.coverage)*Lx/2
    if q<=nx
        i=q
        x=(i-.5)*s.hx-Lx/2; ele=(x>=xl && x<=xr)
        ax[_IX(i,1,nx),b]=ax[_IX(i,2,nx),b]-s.hy*(ele ? hl : s.he)
        ax[_IX(i,ny+1,nx),b]=ax[_IX(i,ny,nx),b]+s.hy*(ele ? hu : s.he)
    end
    if q<=ny
        j=q
        ay[_IY(1,j,nx),b]=ay[_IY(nx,j,nx),b]; ay[_IY(nx+1,j,nx),b]=ay[_IY(2,j,nx),b]
    end
    if q<=ny+1
        j=q
        psi[_I(1,j,nx),b]=psi[_I(nx,j,nx),b]; psi[_I(nx+1,j,nx),b]=psi[_I(2,j,nx),b]
        temp[_I(1,j,nx),b]=temp[_I(nx,j,nx),b]; temp[_I(nx+1,j,nx),b]=temp[_I(2,j,nx),b]
    end
    return
end

function _k_bc_y!(psi,temp,uy,s)
    i=(CUDA.blockIdx().x-1)*CUDA.blockDim().x+CUDA.threadIdx().x
    b=CUDA.blockIdx().y; nx=Int(s.nx); ny=Int(s.ny)
    if i<=nx+1
        lo=_I(i,1,nx); hi=_I(i,ny+1,nx)
        temp[lo,b]=temp[_I(i,2,nx),b]; temp[hi,b]=temp[_I(i,ny,nx),b]
        psi[lo,b]=conj(uy[_IY(i,1,nx),b])*psi[_I(i,2,nx),b]
        psi[hi,b]=uy[_IY(i,ny,nx),b]*psi[_I(i,ny,nx),b]
    end
    return
end

function _k_dpsi!(dpsi,rhs,psi,ax,ay,temp,ux,uy,tc,s)
    q=(CUDA.blockIdx().x-1)*CUDA.blockDim().x+CUDA.threadIdx().x; b=CUDA.blockIdx().y; nx=Int(s.nx); ny=Int(s.ny)
    if q <= (nx+1)*(ny+1)
        i=1+mod(q-1,nx+1); j=1+(q-1)÷(nx+1)
        if i>1 && i<=nx && j>1 && j<=ny
            z=psi[q,b]; l=(conj(ux[_IX(i-1,j,nx),b])*psi[_I(i-1,j,nx),b]-2z+ux[_IX(i,j,nx),b]*psi[_I(i+1,j,nx),b])/(s.hx*s.hx)
            l+=(conj(uy[_IY(i,j-1,nx),b])*psi[_I(i,j-1,nx),b]-2z+uy[_IY(i,j,nx),b]*psi[_I(i,j+1,nx),b])/(s.hy*s.hy)
            e=tc[q,b]-temp[q,b]; r=l+(e-abs2(z))*z; rhs[q,b]=r
            a=s.u/sqrt(1+s.gamma*s.gamma*abs2(z)); rr=r/a; c=real(conj(z)*rr)/(1+s.gamma*s.gamma*abs2(z)); dpsi[q,b]=rr-s.gamma*s.gamma*c*z
        else dpsi[q,b]=0; rhs[q,b]=0 end
    end
    return
end

function _k_current!(jsx,jsy,psi,ux,uy,s)
    q=(CUDA.blockIdx().x-1)*CUDA.blockDim().x+CUDA.threadIdx().x; b=CUDA.blockIdx().y; nx=Int(s.nx); ny=Int(s.ny)
    if q<=nx*(ny+1); i=1+mod(q-1,nx); j=1+(q-1)÷nx; jsx[q,b]=(j>1&&j<=ny) ? imag(conj(psi[_I(i,j,nx),b])*ux[q,b]*psi[_I(i+1,j,nx),b])/s.hx : 0 end
    if q<=(nx+1)*ny; i=1+mod(q-1,nx+1); j=1+(q-1)÷(nx+1); jsy[q,b]=(i>1&&i<=nx) ? imag(conj(psi[_I(i,j,nx),b])*uy[q,b]*psi[_I(i,j+1,nx),b])/s.hy : 0 end
    return
end

function _k_vector!(dax,day,jsx,jsy,ax,ay,sigma,s)
    q=(CUDA.blockIdx().x-1)*CUDA.blockDim().x+CUDA.threadIdx().x; b=CUDA.blockIdx().y; nx=Int(s.nx); ny=Int(s.ny)
    if q<=nx*(ny+1); i=1+mod(q-1,nx); j=1+(q-1)÷nx; dax[q,b]=0; if i>1&&i<nx&&j>1&&j<=ny; dyy=(ax[_IX(i,j+1,nx),b]-2ax[q,b]+ax[_IX(i,j-1,nx),b])/(s.hy*s.hy); dxy=((ay[_IY(i+1,j,nx),b]-ay[_IY(i,j,nx),b])-(ay[_IY(i+1,j-1,nx),b]-ay[_IY(i,j-1,nx),b]))/(s.hx*s.hy); dax[q,b]=(jsx[q,b]+s.kappa*s.kappa*(dyy-dxy))/((sigma[_I(i,j,nx),b]+sigma[_I(i+1,j,nx),b])/2); end end
    if q<=(nx+1)*ny; i=1+mod(q-1,nx+1); j=1+(q-1)÷(nx+1); day[q,b]=0; if i>1&&i<=nx&&j>1&&j<ny; dxx=(ay[_IY(i+1,j,nx),b]-2ay[q,b]+ay[_IY(i-1,j,nx),b])/(s.hx*s.hx); dxy=((ax[_IX(i,j+1,nx),b]-ax[_IX(i-1,j+1,nx),b])-(ax[_IX(i,j,nx),b]-ax[_IX(i-1,j,nx),b]))/(s.hx*s.hy); day[q,b]=(jsy[q,b]+s.kappa*s.kappa*(dxx-dxy))/((sigma[_I(i,j,nx),b]+sigma[_I(i,j+1,nx),b])/2); end end
    return
end

function _k_heat!(dt,w,dpsi,dax,day,psi,temp,eta,sigma,s)
    q=(CUDA.blockIdx().x-1)*CUDA.blockDim().x+CUDA.threadIdx().x; b=CUDA.blockIdx().y; nx=Int(s.nx); ny=Int(s.ny)
    if q<= (nx+1)*(ny+1); i=1+mod(q-1,nx+1); j=1+(q-1)÷(nx+1); dt[q,b]=0; w[q,b]=0; if i>1&&i<=nx&&j>1&&j<=ny; ex=(dax[_IX(i,j,nx),b]+dax[_IX(i-1,j,nx),b])/2; ey=(day[_IY(i,j,nx),b]+day[_IY(i,j-1,nx),b])/2; z=psi[q,b]; da=2*real(conj(z)*dpsi[q,b]); wg=2*s.u/sqrt(1+s.gamma*s.gamma*abs2(z))*(abs2(dpsi[q,b])+s.gamma*s.gamma/4*da*da); ww=2*sigma[q,b]*(ex*ex+ey*ey)+wg; w[q,b]=ww; lap=(temp[_I(i-1,j,nx),b]-2temp[q,b]+temp[_I(i+1,j,nx),b])/(s.hx*s.hx)+(temp[_I(i,j-1,nx),b]-2temp[q,b]+temp[_I(i,j+1,nx),b])/(s.hy*s.hy); dt[q,b]=s.thermal==1 ? (s.keff*lap+.5*ww-eta[q,b]*(temp[q,b]-s.t0))/s.ceff : 0; end end
    return
end

function _k_pack!(du,dpsi,dax,day,dt,s)
    q=(CUDA.blockIdx().x-1)*CUDA.blockDim().x+CUDA.threadIdx().x; b=CUDA.blockIdx().y; nx=Int(s.nx); ny=Int(s.ny); np=(nx+1)*(ny+1); na=nx*(ny+1); nb=(nx+1)*ny
    if q<=np; du[q,b]=dpsi[q,b] elseif q<=np+na; du[q,b]=complex(dax[q-np,b],0) elseif q<=np+na+nb; du[q,b]=complex(day[q-np-na,b],0) elseif q<=np+na+nb+np; du[q,b]=complex(dt[q-np-na-nb,b],0) end
    return
end

function gpu_full_curl_rhs!(du::CuArray{ComplexF64,2}, u::CuArray{ComplexF64,2}, c::GPUFullCurlCache, t)
    size(u)==size(du) || throw(DimensionMismatch("u and du must have identical packed shapes"))
    size(u,2)==length(c.currents) || throw(DimensionMismatch("batch count differs from cache currents"))
    CUDA.allowscalar(false); s=c.s; b=size(u,2); np=(Int(s.nx)+1)*(Int(s.ny)+1); na=Int(s.nx)*(Int(s.ny)+1); nb=(Int(s.nx)+1)*Int(s.ny); packed=2*np+na+nb; th=256
    @cuda threads=th blocks=(cld(packed,th),b) _k_unpack!(du,u,c.psi,c.ax,c.ay,c.temp,c.ux,c.uy,s)
    @cuda threads=th blocks=(cld(max(size(c.ux,1),size(c.uy,1)),th),b) _k_links!(c.psi,c.ax,c.ay,c.temp,c.ux,c.uy,s)
    @cuda threads=128 blocks=(cld(max(Int(s.nx),Int(s.ny)+1),128),b) _k_bc_x!(c.psi,c.ax,c.ay,c.temp,c.currents,s)
    @cuda threads=128 blocks=(cld(Int(s.nx)+1,128),b) _k_bc_y!(c.psi,c.temp,c.uy,s)
    # As in the frozen CPU RHS, use the links sampled before reconstructing
    # boundaries. Rebuilding all links here would be redundant for the
    # supported interior stencil and would obscure that ordering contract.
    @cuda threads=th blocks=(cld(np,th),b) _k_dpsi!(c.dpsi,c.rhspsi,c.psi,c.ax,c.ay,c.temp,c.ux,c.uy,c.tc,s)
    @cuda threads=th blocks=(cld(max(size(c.jsx,1),size(c.jsy,1)),th),b) _k_current!(c.jsx,c.jsy,c.psi,c.ux,c.uy,s)
    @cuda threads=th blocks=(cld(max(size(c.dax,1),size(c.day,1)),th),b) _k_vector!(c.dax,c.day,c.jsx,c.jsy,c.ax,c.ay,c.sigma,s)
    @cuda threads=th blocks=(cld(np,th),b) _k_heat!(c.dt,c.w,c.dpsi,c.dax,c.day,c.psi,c.temp,c.eta,c.sigma,s)
    @cuda threads=th blocks=(cld(packed,th),b) _k_pack!(du,c.dpsi,c.dax,c.day,c.dt,s)
    return du
end
